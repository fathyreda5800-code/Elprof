create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'student' check (role in ('student', 'teacher')),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

create policy "profiles_read_own"
  on public.profiles for select
  using (auth.uid() = id);

create policy "profiles_update_own"
  on public.profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

revoke update on table public.profiles from authenticated;
grant update (full_name) on table public.profiles to authenticated;

create table if not exists public.models (
  id bigint generated by default as identity primary key,
  title text not null,
  subject text not null default 'القدرات العامة والتحصيلي',
  description text not null default '',
  question_count integer not null default 0,
  duration integer not null default 0,
  is_published boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.models enable row level security;

create policy "models_read_published"
  on public.models for select
  using (is_published = true);

create policy "models_teacher_insert"
  on public.models for insert
  with check (
    exists (
      select 1 from public.profiles
      where profiles.id = auth.uid() and profiles.role = 'teacher'
    )
  );

create policy "models_teacher_update"
  on public.models for update
  using (
    exists (
      select 1 from public.profiles
      where profiles.id = auth.uid() and profiles.role = 'teacher'
    )
  );

create policy "models_teacher_delete"
  on public.models for delete
  using (
    exists (
      select 1 from public.profiles
      where profiles.id = auth.uid() and profiles.role = 'teacher'
    )
  );

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  model_id bigint not null references public.models(id) on delete cascade,
  position integer not null,
  text text not null,
  options jsonb not null,
  correct_index integer not null,
  explanation text not null default '',
  created_at timestamptz not null default now(),
  unique (model_id, position)
);

alter table public.questions enable row level security;

create policy "questions_read_published_models"
  on public.questions for select
